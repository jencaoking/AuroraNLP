        for marker in tw_markers:
            if marker in text:
                scores['tw'] += 1
        
        for marker in hk_markers:
            if marker in text:
                scores['hk'] += 1
        
        for marker in mo_markers:
            if marker in text:
                scores['mo'] += 1
        
        # 返回得分最高的地区
        max_score = max(scores.values())
        if max_score > 0:
            return max(scores, key=scores.get)
        return None
    
