class TraditionalChineseDictionary:
    """
    繁体中文词典类
    """
    
    def __init__(self, converter: Optional[TraditionalChineseConverter] = None):
        self._converter = converter or TraditionalChineseConverter()
        self._dictionary = set()
    
    def add_word(self, word: str, traditional: Optional[str] = None) -> None:
        """
        添加词汇到词典
        
        Args:
            word: 词汇（可以是简体或繁体）
            traditional: 对应的繁体形式（可选）
        """
        if traditional:
            self._dictionary.add(traditional)
        else:
            # 自动转换为繁体
            traditional_word = self._converter.simplified_to_traditional(word)
            self._dictionary.add(traditional_word)
    
    def add_words(self, words: List[str]) -> None:
        """
        批量添加词汇
        
        Args:
            words: 词汇列表
        """
        for word in words:
            self.add_word(word)
    
    def contains(self, word: str) -> bool:
        """
        检查词典是否包含指定词汇
        
        Args:
            word: 要检查的词汇
            
        Returns:
            是否包含
        """
        # 转换为繁体后检查
        traditional_word = self._converter.simplified_to_traditional(word)
        return traditional_word in self._dictionary
    
    def get_words(self) -> Set[str]:
        """
        获取所有词汇
        
        Returns:
            词汇集合
        """
        return self._dictionary.copy()
    
    def load_from_file(self, file_path: str) -> int:
        """
        从文件加载词典
        
        Args:
            file_path: 文件路径
            
        Returns:
            加载的词汇数量
        """
        count = 0
        if os.path.exists(file_path):
            with open(file_path, 'r', encoding='utf-8') as f:
                for line in f:
                    word = line.strip()
                    if word:
                        self.add_word(word)
                        count += 1
        return count
    
    def save_to_file(self, file_path: str) -> None:
        """
        保存词典到文件
        
        Args:
            file_path: 文件路径
        """
        with open(file_path, 'w', encoding='utf-8') as f:
            for word in sorted(self._dictionary):
                f.write(f"{word}\n")
